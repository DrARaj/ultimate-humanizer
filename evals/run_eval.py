"""Run scripts/lint.py over evals/data and write evals/results.json and evals/RESULTS.md.
Stdlib only. Run from the repo root: python evals/run_eval.py"""
import csv, hashlib, importlib.util, json, subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EVALS = ROOT / "evals"
SETS = ["human-wiki", "human-abstracts", "ai"]
HUMAN = ("human-wiki", "human-abstracts")

spec = importlib.util.spec_from_file_location("lint", ROOT / "scripts" / "lint.py")
lint = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lint)

rows = list(csv.DictReader(open(EVALS / "data" / "manifest.csv", encoding="utf-8")))
res = []
for r in rows:
    text = (EVALS / "data" / f"{r['id']}.txt").read_text(encoding="utf-8")
    hits = lint.lint(text)
    res.append({"id": r["id"], "set": r["set"], "topic": r["topic"], "words": len(text.split()),
                "fail": [[ln, c, rule, m] for ln, c, lv, rule, m in hits if lv == "FAIL"],
                "check": [[ln, c, rule, m] for ln, c, lv, rule, m in hits if lv == "CHECK"]})


def pct(n, d):
    return 100.0 * n / d if d else 0.0


def summary(group):
    n = len(group)
    words = sum(p["words"] for p in group)
    fails = sum(len(p["fail"]) for p in group)
    return {"passages": n, "words": words, "total_fail": fails,
            "pct_any_fail": pct(sum(bool(p["fail"]) for p in group), n),
            "pct_any_fail_or_check": pct(sum(bool(p["fail"] or p["check"]) for p in group), n),
            "fail_per_100_words": pct(fails, words)}


groups = {s: [p for p in res if p["set"] == s] for s in SETS}
groups["human (both sets)"] = [p for p in res if p["set"] in HUMAN]
summ = {k: summary(v) for k, v in groups.items()}

# per rule: share of passages with at least one hit of that rule and level
per_rule = defaultdict(lambda: {"human": 0, "ai": 0})
for p in res:
    side = "human" if p["set"] in HUMAN else "ai"
    for level in ("fail", "check"):
        for rule in {h[2] for h in p[level]}:
            per_rule[(level.upper(), rule)][side] += 1
n_h, n_a = len(groups["human (both sets)"]), len(groups["ai"])
table = []
for (level, rule), c in per_rule.items():
    hr, ar = pct(c["human"], n_h), pct(c["ai"], n_a)
    table.append({"level": level, "rule": rule, "human_passages": c["human"], "human_rate": hr,
                  "ai_passages": c["ai"], "ai_rate": ar,
                  "fp_prone": c["human"] > 0 and hr >= 0.25 * ar})
table.sort(key=lambda t: (t["level"] != "FAIL", -t["human_rate"], -t["ai_rate"]))

# matched phrases behind each human FAIL, per rule
phrases = defaultdict(lambda: defaultdict(int))
for p in groups["human (both sets)"]:
    for _l, _c, rule, m in p["fail"]:
        phrases[rule][m.lower()] += 1

top = sorted(groups["human (both sets)"], key=lambda p: -len(p["fail"]))[:5]


def lint_sha():
    return hashlib.sha256((ROOT / "scripts" / "lint.py").read_bytes()).hexdigest()[:12]


def commit():
    try:
        return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True).stdout.strip()
    except OSError:
        return ""


json.dump({"lint_sha256_12": lint_sha(), "repo_commit": commit(), "summary": summ,
           "per_rule": table, "passages": res}, open(EVALS / "results.json", "w", encoding="utf-8"),
          indent=1)

L = []
w = L.append
w("# Lint evaluation: human text and AI text\n")
w("This page reports how often `scripts/lint.py` flags text that people wrote, compared with text a model wrote. "
  f"It was generated by `evals/run_eval.py` (lint.py hash {lint_sha()}). Data and method are in `evals/README.md`.\n")
w("## Headline\n")
w("| Set | Passages | Words | With at least one FAIL | With a FAIL or CHECK | FAIL per 100 words |")
w("|---|---|---|---|---|---|")
for k, s in summ.items():
    w(f"| {k} | {s['passages']} | {s['words']} | {s['pct_any_fail']:.0f}% | "
      f"{s['pct_any_fail_or_check']:.0f}% | {s['fail_per_100_words']:.2f} |")
w("")
w("## Per-rule hits\n")
w(f"Each cell is the number of passages with at least one hit for that rule and level. Human is the {n_h} human "
  f"passages together, AI is the {n_a} AI passages. A rule is marked false-positive prone when its human hit rate "
  "is at least 25% of its AI hit rate, or when it hits human text and never hits AI text.\n")
w("| Level | Rule | Human passages | Human rate | AI passages | AI rate | Flag |")
w("|---|---|---|---|---|---|---|")
for t in table:
    w(f"| {t['level']} | {t['rule']} | {t['human_passages']} | {t['human_rate']:.0f}% | "
      f"{t['ai_passages']} | {t['ai_rate']:.0f}% | {'false-positive prone' if t['fp_prone'] else ''} |")
w("")
w("## What matched in human text\n")
w("Phrases behind the human FAIL hits, with counts.\n")
for rule in sorted(phrases, key=lambda r: -sum(phrases[r].values())):
    items = ", ".join(f"{m} ({n})" for m, n in sorted(phrases[rule].items(), key=lambda x: -x[1])[:8])
    w(f"- {rule}: {items}")
w("")
w("## Five human passages with the most FAILs\n")
for p in top:
    w(f"- {p['id']} ({p['topic']}, {p['set']}, {p['words']} words): {len(p['fail'])} FAIL")
    for _l, _c, rule, m in p["fail"][:6]:
        w(f"  - {rule}: {m!r}")
w("")
w("## Limits\n")
w("- This measures the linter only. It does not test whether the skill rewrites text well.")
w("- The AI text comes from one model (Claude Haiku) and one plain prompt, one passage per topic. Other models, "
  "prompts and edits would give different rates.")
w("- Wikipedia text is written and edited by many people, and some of it follows house style. Abstracts are "
  "scientific prose. Neither set stands for all human writing.")
w("- Sample sizes are small (40, 20 and 40 passages), so a rate of a few percent is one or two passages.")
w("- The numbers are not an AI detector. Lint flags are evidence, not proof, and a flagged human passage shows "
  "that these tells also occur in ordinary writing.")
(EVALS / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote evals/results.json and evals/RESULTS.md")
for k, s in summ.items():
    print(f"{k}: {s['pct_any_fail']:.0f}% FAIL, {s['pct_any_fail_or_check']:.0f}% FAIL/CHECK, {s['fail_per_100_words']:.2f}/100w")
